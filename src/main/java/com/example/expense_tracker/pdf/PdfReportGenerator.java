package com.example.expense_tracker.pdf;

import com.example.expense_tracker.dto.TransactionResponse;
import com.example.expense_tracker.dto.response.MonthlyReportResponse;
import com.lowagie.text.*;
import com.lowagie.text.pdf.*;

import org.springframework.stereotype.Component;

import java.io.ByteArrayOutputStream;

@Component
public class PdfReportGenerator {

    public byte[] generate(MonthlyReportResponse report) {

        try {

            ByteArrayOutputStream outputStream = new ByteArrayOutputStream();

            Document document = new Document(PageSize.A4);

            PdfWriter.getInstance(document, outputStream);

            document.open();

            Font titleFont = new Font(Font.HELVETICA,20,Font.BOLD);
            Font headingFont = new Font(Font.HELVETICA,14,Font.BOLD);
            Font normalFont = new Font(Font.HELVETICA,12);

            Paragraph title = new Paragraph(
                    "FinTrack Monthly Financial Report",
                    titleFont
            );

            title.setAlignment(Element.ALIGN_CENTER);

            document.add(title);

            document.add(new Paragraph(" "));

            document.add(new Paragraph(
                    "Month : " + report.getMonth(),
                    headingFont
            ));

            document.add(new Paragraph(" "));

            document.add(new Paragraph(
                    "Total Income : ₹ " + report.getTotalIncome(),
                    normalFont
            ));

            document.add(new Paragraph(
                    "Total Expense : ₹ " + report.getTotalExpense(),
                    normalFont
            ));

            document.add(new Paragraph(
                    "Savings : ₹ " + report.getTotalSavings(),
                    normalFont
            ));

            document.add(new Paragraph(
                    "Highest Expense : ₹ " + report.getHighestExpense(),
                    normalFont
            ));

            document.add(new Paragraph(
                    "Average Daily Expense : ₹ "
                            + report.getAverageDailyExpense(),
                    normalFont
            ));

            document.add(new Paragraph(" "));

            document.add(new Paragraph(
                    "Top Category : "
                            + report.getTopExpenseCategory(),
                    headingFont
            ));

            document.add(new Paragraph(
                    "Top Payment Method : "
                            + report.getTopPaymentMethod(),
                    headingFont
            ));

            document.add(new Paragraph(" "));

            PdfPTable table = new PdfPTable(4);

            table.setWidthPercentage(100);

            table.addCell("Date");
            table.addCell("Title");
            table.addCell("Type");
            table.addCell("Amount");

            for (TransactionResponse transaction
                    : report.getTransactions()) {

                table.addCell(
                        transaction.getTransactionDate().toString()
                );

                table.addCell(
                        transaction.getTitle()
                );

                table.addCell(
                        transaction.getType().name()
                );

                table.addCell(
                        "₹ " + transaction.getAmount()
                );

            }

            document.add(table);

            document.add(new Paragraph(" "));

            Paragraph footer = new Paragraph(
                    "Generated by FinTrack",
                    headingFont
            );

            footer.setAlignment(Element.ALIGN_CENTER);

            document.add(footer);

            document.close();

            return outputStream.toByteArray();

        }
        catch (Exception ex){

            throw new RuntimeException(ex);

        }

    }

}